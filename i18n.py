# Match whole templates so user messages, paths and channel names stay untouched.
TEMPLATES = []
for source, target in EN.items():
    fields = re.findall(r'\{(\w+)\}', source)
    if fields:
        pattern = re.escape(source)
        for field in fields:
            pattern = pattern.replace(re.escape('{'+field+'}'), '(?P<'+field+'>.+?)')
        TEMPLATES.append((re.compile('^'+pattern+'$', re.DOTALL), target))

def translate(text, language):
    if language != 'English':
        return str(text)
    text = str(text)
    if text in EN:
        return EN[text]
    for pattern, target in TEMPLATES:
        match = pattern.fullmatch(text)
        if match:
            values = match.groupdict()
            if 'detail' in values:
                values['detail'] = translate(values['detail'], language)
            return target.format(**values)
    for prefix in ('✕ ', '✓ '):
        if text.startswith(prefix):
            return prefix + translate(text[len(prefix):], language)
    return text
